"""Fit temperature scaling on one season, then evaluate only on later seasons.

Run from the repository root:
    python -m src.calibration_experiment --calibration-season 2021-2022

This script reads the per-match CSVs generated by src.evaluate_models and does
not connect to or modify PostgreSQL. The calibration temperature is fitted using
only the designated calibration season. Metrics used to judge the adjustment are
reported only on later held-out seasons.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

import numpy as np
import pandas as pd

DEFAULT_INPUTS = [
    "reports/backtest_2021-2022.csv",
    "reports/backtest_2022-2023.csv",
    "reports/backtest_2023-2024.csv",
    "reports/backtest_2024-2025.csv",
]
SIDES = ("home", "draw", "away")
METRICS = ("brier", "rps", "log_loss")


def season_start_year(season: str) -> int:
    try:
        return int(str(season).split("-")[0])
    except (ValueError, IndexError) as exc:
        raise ValueError(f"Invalid season label {season!r}; expected e.g. 2021-2022") from exc


def outcome_from_goals(home_goals: int, away_goals: int) -> str:
    if home_goals > away_goals:
        return "HOME"
    if home_goals == away_goals:
        return "DRAW"
    return "AWAY"


def validate_probability_columns(frame: pd.DataFrame, prefix: str) -> None:
    cols = [f"{prefix}_p_{side}" for side in SIDES]
    values = frame[cols].to_numpy(dtype=float)
    if not np.isfinite(values).all():
        raise ValueError(f"Non-finite probabilities in {cols}")
    if (values < 0).any() or (values > 1).any():
        raise ValueError(f"Probabilities outside [0, 1] in {cols}")
    if not np.allclose(values.sum(axis=1), 1.0, atol=1e-6, rtol=0):
        raise ValueError(f"Probabilities in {cols} must sum to 1 for every row")


def load_reports(paths: list[str]) -> pd.DataFrame:
    required = {
        "match_id", "season", "match_date_utc", "home_goals", "away_goals",
        "dc_p_home", "dc_p_draw", "dc_p_away",
        "baseline_p_home", "baseline_p_draw", "baseline_p_away",
        "baseline_brier", "baseline_rps", "baseline_log_loss",
    }
    if not paths:
        raise ValueError("Provide at least one input report")

    frames = []
    for value in paths:
        path = Path(value)
        if not path.is_file():
            raise FileNotFoundError(f"Backtest report not found: {path}")
        frame = pd.read_csv(path, dtype={"season": str, "match_date_utc": str})
        missing = sorted(required - set(frame.columns))
        if missing:
            raise ValueError(f"{path} is missing required columns: {missing}")
        if frame.empty:
            raise ValueError(f"Backtest report is empty: {path}")
        frames.append(frame)

    data = pd.concat(frames, ignore_index=True)
    data["season"] = data["season"].astype(str)
    data["match_date_utc"] = data["match_date_utc"].astype(str)
    data["home_goals"] = pd.to_numeric(data["home_goals"], errors="raise")
    data["away_goals"] = pd.to_numeric(data["away_goals"], errors="raise")
    if not np.isfinite(data[["home_goals", "away_goals"]].to_numpy(dtype=float)).all():
        raise ValueError("Goal columns contain non-finite values")
    if ((data[["home_goals", "away_goals"]] < 0).any().any()
            or not np.equal(data["home_goals"], np.floor(data["home_goals"])).all()
            or not np.equal(data["away_goals"], np.floor(data["away_goals"])).all()):
        raise ValueError("Goals must be non-negative integers")

    numeric_columns = [
        *[f"{prefix}_p_{side}" for prefix in ("dc", "baseline") for side in SIDES],
        *[f"baseline_{metric}" for metric in METRICS],
    ]
    for column in numeric_columns:
        data[column] = pd.to_numeric(data[column], errors="raise")
    if not np.isfinite(data[numeric_columns].to_numpy(dtype=float)).all():
        raise ValueError("Input reports contain NaN or infinite numbers")
    validate_probability_columns(data, "dc")
    validate_probability_columns(data, "baseline")

    if data.duplicated(["season", "match_id"]).any():
        duplicated = data.loc[data.duplicated(["season", "match_id"], keep=False), ["season", "match_id"]]
        raise ValueError("Duplicate fixture rows across reports:\n" + duplicated.to_string(index=False))

    data["actual_outcome"] = [
        outcome_from_goals(int(h), int(a))
        for h, a in zip(data["home_goals"], data["away_goals"])
    ]
    return data


def temperature_scale(probabilities: np.ndarray, temperature: float) -> np.ndarray:
    """Apply multiclass temperature scaling to rows of 1X2 probabilities."""
    if not np.isfinite(temperature) or temperature <= 0:
        raise ValueError("Temperature must be a positive finite number")
    p = np.asarray(probabilities, dtype=float)
    if p.ndim != 2 or p.shape[1] != 3:
        raise ValueError("Expected an N x 3 probability matrix in HOME, DRAW, AWAY order")
    # Clipping only protects log(0); rows are normalized again after softmax.
    logits = np.log(np.clip(p, 1e-15, 1.0)) / float(temperature)
    logits -= logits.max(axis=1, keepdims=True)
    exp_logits = np.exp(logits)
    scaled = exp_logits / exp_logits.sum(axis=1, keepdims=True)
    if not np.isfinite(scaled).all() or not np.allclose(scaled.sum(axis=1), 1.0, atol=1e-12):
        raise ValueError("Temperature scaling produced invalid probabilities")
    return scaled


def log_loss_rows(probabilities: np.ndarray, outcomes: np.ndarray) -> np.ndarray:
    indexes = {"HOME": 0, "DRAW": 1, "AWAY": 2}
    chosen = np.array([probabilities[i, indexes[o]] for i, o in enumerate(outcomes)], dtype=float)
    return -np.log(np.clip(chosen, 1e-15, 1.0))


def calculate_metrics(probabilities: np.ndarray, outcomes: np.ndarray) -> dict[str, float]:
    """Match the project's 3-class Brier, normalized RPS, and log-loss definitions."""
    order = {"HOME": 0, "DRAW": 1, "AWAY": 2}
    actual = np.zeros_like(probabilities, dtype=float)
    for row, outcome in enumerate(outcomes):
        actual[row, order[outcome]] = 1.0

    brier = ((probabilities - actual) ** 2).sum(axis=1)
    # Three ordered categories: average squared error over the first two cumulative probabilities.
    cumulative_pred = np.cumsum(probabilities, axis=1)[:, :2]
    cumulative_actual = np.cumsum(actual, axis=1)[:, :2]
    rps = ((cumulative_pred - cumulative_actual) ** 2).mean(axis=1)
    ll = log_loss_rows(probabilities, outcomes)
    return {
        "brier": float(brier.mean()),
        "rps": float(rps.mean()),
        "log_loss": float(ll.mean()),
    }


def fit_temperature(frame: pd.DataFrame, lower: float, upper: float) -> tuple[float, float, float]:
    """Fit one scalar T by minimizing multiclass log loss on the calibration season."""
    try:
        from scipy.optimize import minimize_scalar
    except ImportError as exc:
        raise RuntimeError("SciPy is required; install it with `pip install scipy`") from exc

    p = frame[["dc_p_home", "dc_p_draw", "dc_p_away"]].to_numpy(dtype=float)
    y = frame["actual_outcome"].to_numpy(dtype=str)
    raw_nll = float(log_loss_rows(p, y).mean())

    result = minimize_scalar(
        lambda temp: float(log_loss_rows(temperature_scale(p, float(temp)), y).mean()),
        bounds=(lower, upper),
        method="bounded",
        options={"xatol": 1e-8, "maxiter": 1000},
    )
    if not result.success or not np.isfinite(result.x) or not np.isfinite(result.fun):
        raise RuntimeError(f"Could not fit temperature parameter: {result.message}")
    return float(result.x), raw_nll, float(result.fun)


def paired_date_bootstrap(
    test: pd.DataFrame,
    calibrated_probs: np.ndarray,
    reps: int,
    seed: int,
) -> pd.DataFrame:
    """Date-cluster bootstrap for calibrated minus raw score differences.

    For the pooled test scope, resample dates independently within each held-out
    season so that all three test seasons remain represented in every replicate.
    """
    raw_probs = test[["dc_p_home", "dc_p_draw", "dc_p_away"]].to_numpy(dtype=float)
    outcomes = test["actual_outcome"].to_numpy(dtype=str)
    order = {"HOME": 0, "DRAW": 1, "AWAY": 2}
    actual = np.zeros_like(raw_probs, dtype=float)
    for row, outcome in enumerate(outcomes):
        actual[row, order[outcome]] = 1.0

    def per_row_metrics(p: np.ndarray) -> dict[str, np.ndarray]:
        brier = ((p - actual) ** 2).sum(axis=1)
        rps = ((np.cumsum(p, axis=1)[:, :2] - np.cumsum(actual, axis=1)[:, :2]) ** 2).mean(axis=1)
        ll = log_loss_rows(p, outcomes)
        return {"brier": brier, "rps": rps, "log_loss": ll}

    raw_by_metric = per_row_metrics(raw_probs)
    cal_by_metric = per_row_metrics(calibrated_probs)
    differences = {m: cal_by_metric[m] - raw_by_metric[m] for m in METRICS}
    test = test.reset_index(drop=True)

    scopes: list[tuple[str, list[pd.DataFrame]]] = []
    for season, sf in test.groupby("season", sort=True):
        scopes.append((str(season), [g for _, g in sf.groupby("match_date_utc", sort=True)]))
    pooled_groups = [g for _, sf in test.groupby("season", sort=True)
                     for _, g in sf.groupby("match_date_utc", sort=True)]
    # ALL_TEST_SEASONS handled separately with resampling within season below.
    scopes.append(("ALL_TEST_SEASONS", []))

    rng = np.random.default_rng(seed)
    rows = []

    def add_scope(scope: str, subset_indexes: np.ndarray, cluster_indexes: list[np.ndarray], preserve_seasons: bool):
        deltas = {m: differences[m][subset_indexes] for m in METRICS}
        point = {m: float(v.mean()) for m, v in deltas.items()}
        draws = {m: np.empty(reps, dtype=float) for m in METRICS}

        if preserve_seasons:
            season_clusters = []
            season_labels = test.iloc[subset_indexes]["season"].to_numpy()
            for season in sorted(set(season_labels)):
                local_positions = np.flatnonzero(season_labels == season)
                by_date = test.iloc[subset_indexes].iloc[local_positions].groupby("match_date_utc", sort=True).indices
                c = [local_positions[np.asarray(indices, dtype=int)] for indices in by_date.values()]
                season_clusters.append(c)
        else:
            season_clusters = [cluster_indexes]

        for b in range(reps):
            sampled_values = {m: [] for m in METRICS}
            for clusters in season_clusters:
                if not clusters:
                    continue
                chosen = rng.integers(0, len(clusters), size=len(clusters))
                for idx in chosen:
                    for metric in METRICS:
                        sampled_values[metric].extend(differences[metric][clusters[idx]].tolist())
            for metric in METRICS:
                draws[metric][b] = float(np.mean(sampled_values[metric]))

        for metric in METRICS:
            lo, hi = np.quantile(draws[metric], [0.025, 0.975])
            rows.append({
                "scope": scope,
                "metric": metric,
                "n": len(subset_indexes),
                "mean_difference_calibrated_minus_raw": point[metric],
                "ci95_lower": float(lo),
                "ci95_upper": float(hi),
                "bootstrap_reps": reps,
                "cluster_unit": "match_date_utc",
            })

    for season, clusters in scopes:
        if season == "ALL_TEST_SEASONS":
            subset_indexes = np.arange(len(test), dtype=int)
            add_scope(season, subset_indexes, pooled_groups, preserve_seasons=True)
        else:
            indexes = np.flatnonzero(test["season"].to_numpy() == season)
            date_groups = test.iloc[indexes].groupby("match_date_utc", sort=True).indices
            local_clusters = [indexes[np.asarray(ix, dtype=int)] for ix in date_groups.values()]
            add_scope(season, indexes, local_clusters, preserve_seasons=False)
    return pd.DataFrame(rows)


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inputs", nargs="+", default=DEFAULT_INPUTS,
                        help="per-match backtest CSVs generated by src.evaluate_models")
    parser.add_argument("--calibration-season", default="2021-2022",
                        help="season used only to fit temperature (default: 2021-2022)")
    parser.add_argument("--min-temperature", type=float, default=0.25,
                        help="lower bound for temperature fit (default: 0.25)")
    parser.add_argument("--max-temperature", type=float, default=4.0,
                        help="upper bound for temperature fit (default: 4.0)")
    parser.add_argument("--bootstrap-reps", type=int, default=2000,
                        help="date-cluster bootstrap repetitions (default: 2000)")
    parser.add_argument("--seed", type=int, default=20261023)
    parser.add_argument("--output-dir", default="reports")
    return parser.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)
    try:
        if args.bootstrap_reps < 100:
            raise ValueError("--bootstrap-reps must be at least 100")
        if not (0 < args.min_temperature < args.max_temperature):
            raise ValueError("Temperature bounds must satisfy 0 < min < max")

        data = load_reports(args.inputs)
        calibration_matches = data[data["season"] == str(args.calibration_season)].copy()
        if calibration_matches.empty:
            raise ValueError(
                f"Calibration season {args.calibration_season!r} was not found in the reports. "
                f"Available seasons: {sorted(data['season'].unique())}"
            )

        cal_start = season_start_year(args.calibration_season)
        test = data[data["season"].map(season_start_year) > cal_start].copy()
        if test.empty:
            raise ValueError("No seasons later than the calibration season are available for held-out testing")
        earlier = data[data["season"].map(season_start_year) < cal_start]
        if not earlier.empty:
            print("Note: excluding seasons earlier than the calibration season:",
                  ", ".join(sorted(earlier["season"].unique())))

        temperature, cal_raw_nll, cal_scaled_nll = fit_temperature(
            calibration_matches, args.min_temperature, args.max_temperature
        )
        raw_cal = calibration_matches[["dc_p_home", "dc_p_draw", "dc_p_away"]].to_numpy(dtype=float)
        scaled_cal = temperature_scale(raw_cal, temperature)
        if not np.allclose(scaled_cal.sum(axis=1), 1.0, atol=1e-12, rtol=0):
            raise ValueError("Calibrated probabilities do not sum to one")

        raw_test = test[["dc_p_home", "dc_p_draw", "dc_p_away"]].to_numpy(dtype=float)
        outcomes_test = test["actual_outcome"].to_numpy(dtype=str)
        scaled_test = temperature_scale(raw_test, temperature)

        # Recompute metrics on held-out data rather than trusting precomputed score columns.
        predictions = test[["match_id", "season", "match_date_utc", "home_goals", "away_goals",
                            "actual_outcome", "dc_p_home", "dc_p_draw", "dc_p_away",
                            "baseline_p_home", "baseline_p_draw", "baseline_p_away"]].copy()
        predictions["cal_p_home"] = scaled_test[:, 0]
        predictions["cal_p_draw"] = scaled_test[:, 1]
        predictions["cal_p_away"] = scaled_test[:, 2]

        summary_rows = []
        for season in sorted(test["season"].unique(), key=season_start_year):
            mask = test["season"].to_numpy() == season
            season_frame = test.loc[mask]
            all_probs = {
                "dixon_coles_raw": raw_test[mask],
                "dixon_coles_temperature_scaled": scaled_test[mask],
                "baseline_poisson_v1": season_frame[["baseline_p_home", "baseline_p_draw", "baseline_p_away"]].to_numpy(dtype=float),
            }
            season_outcomes = outcomes_test[mask]
            for model, probabilities in all_probs.items():
                scores = calculate_metrics(probabilities, season_outcomes)
                summary_rows.append({"scope": str(season), "model": model, "n": len(season_frame), **scores})
                for metric in METRICS:
                    predictions.loc[mask, f"{model}_{metric}"] = np.nan  # columns created explicitly below
                    # Use array-based scoring below to retain per-match records.
                    if metric == "brier":
                        order = {"HOME": 0, "DRAW": 1, "AWAY": 2}
                        actual = np.zeros_like(probabilities)
                        for i, outcome in enumerate(season_outcomes):
                            actual[i, order[outcome]] = 1.0
                        row_scores = ((probabilities - actual) ** 2).sum(axis=1)
                    elif metric == "rps":
                        order = {"HOME": 0, "DRAW": 1, "AWAY": 2}
                        actual = np.zeros_like(probabilities)
                        for i, outcome in enumerate(season_outcomes):
                            actual[i, order[outcome]] = 1.0
                        row_scores = ((np.cumsum(probabilities, axis=1)[:, :2] - np.cumsum(actual, axis=1)[:, :2]) ** 2).mean(axis=1)
                    else:
                        row_scores = log_loss_rows(probabilities, season_outcomes)
                    predictions.loc[mask, f"{model}_{metric}"] = row_scores

        # Pooled held-out scope.
        for model, probabilities in (
            ("dixon_coles_raw", raw_test),
            ("dixon_coles_temperature_scaled", scaled_test),
            ("baseline_poisson_v1", test[["baseline_p_home", "baseline_p_draw", "baseline_p_away"]].to_numpy(dtype=float)),
        ):
            summary_rows.append({"scope": "ALL_TEST_SEASONS", "model": model, "n": len(test),
                                 **calculate_metrics(probabilities, outcomes_test)})

        summary = pd.DataFrame(summary_rows)
        uncertainty = paired_date_bootstrap(test.reset_index(drop=True), scaled_test,
                                             args.bootstrap_reps, args.seed)
        output_dir = Path(args.output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)
        summary_path = output_dir / "calibration_experiment_summary.csv"
        uncertainty_path = output_dir / "calibration_experiment_paired_uncertainty.csv"
        predictions_path = output_dir / "calibration_experiment_predictions.csv"
        summary.to_csv(summary_path, index=False, float_format="%.10g")
        uncertainty.to_csv(uncertainty_path, index=False, float_format="%.10g")
        predictions.to_csv(predictions_path, index=False, float_format="%.10g")

        print("OUT-OF-SAMPLE TEMPERATURE-SCALING EXPERIMENT")
        print(f"Calibration season: {args.calibration_season} ({len(calibration_matches)} fixtures)")
        print(f"Fitted temperature: {temperature:.6f} (bounds {args.min_temperature:g} to {args.max_temperature:g})")
        print("Calibration-season fit diagnostics (in-sample; not evidence of generalization):")
        print(f"  Raw log loss:        {cal_raw_nll:.6f}")
        print(f"  Scaled log loss:     {cal_scaled_nll:.6f}")
        print(f"Held-out seasons: {', '.join(sorted(test['season'].unique(), key=season_start_year))}")
        print(f"Held-out fixtures: {len(test)}")
        print("\nHeld-out mean scores (lower is better):")
        print(summary.round(5).to_string(index=False))
        print("\nPaired score differences (temperature-scaled Dixon-Coles minus raw Dixon-Coles)")
        print("Negative differences favour temperature scaling; intervals resample UTC date clusters.")
        print(uncertainty.round(5).to_string(index=False))
        print("\nReports saved:")
        print(f"  Summary:     {summary_path}")
        print(f"  Uncertainty: {uncertainty_path}")
        print(f"  Predictions: {predictions_path}")
        print("This experiment does not alter PostgreSQL or locked predictions.")
        return 0
    except Exception as exc:
        print(f"Calibration experiment failed: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
