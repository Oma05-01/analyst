"""
Premier League prediction API.

Run from the repository root:   uvicorn src.api.main:app --reload

Design rules
  * Read-only. No endpoint writes to the database and none calls the LLM: previews are
    generated by the pipeline at lock time and read from match_previews.
  * One row per match: every query filters on the primary model_version, because the
    baseline (and older versions) also store a prediction for each match.
  * A small connection pool with a hard cap, so a crowd cannot exhaust the free-tier
    database's connection limit. Requests beyond the cap wait briefly, then get a 503.
  * Short in-memory caching plus Cache-Control headers, so most traffic never reaches
    the database.
  * Missing data is returned as null, never as a made-up placeholder.
"""
