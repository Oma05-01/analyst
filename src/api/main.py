# ----------------------------------------------------------------------- database pool
_pool = None
_pool_lock = threading.Lock()
_slots = threading.BoundedSemaphore(POOL_MAX)


def _get_pool():
    global _pool
    if _pool is None:
        with _pool_lock:
            if _pool is None:
                url = os.getenv("DATABASE_URL")
                if not url:
                    raise RuntimeError("DATABASE_URL is not set")
                _pool = pool.ThreadedConnectionPool(1, POOL_MAX, dsn=url)
    return _pool


@contextmanager
def db_cursor():
    if not _slots.acquire(timeout=SLOT_WAIT_SECONDS):
        raise HTTPException(status_code=503, detail="Server is busy, please retry shortly")
    conn = None
    try:
        conn = _get_pool().getconn()
        try:                                   # free-tier databases drop idle connections
            with conn.cursor() as ping:
                ping.execute("SELECT 1")
        except Exception:
            _get_pool().putconn(conn, close=True)
            conn = _get_pool().getconn()
        with conn.cursor() as cur:
            yield cur
    finally:
        if conn is not None:
            try:
                conn.rollback()
            finally:
                _get_pool().putconn(conn)
        _slots.release()


# ---------------------------------------------------------------------------- caching
_cache = {}


def cached(key, ttl_seconds, producer):
    now = time.monotonic()
    hit = _cache.get(key)
    if hit and now - hit[0] < ttl_seconds:
        return hit[1]
    value = producer()
    _cache[key] = (now, value)
    return value


def public_cache(response: Response, seconds):
    response.headers["Cache-Control"] = f"public, max-age={seconds}"


# ----------------------------------------------------------------------------- helpers
def iso(moment):
    return utc_iso(moment) if moment is not None else None


def as_matrix(raw):
    return json.loads(raw) if isinstance(raw, str) else raw


def fnum(value):
    return float(value) if value is not None else None

def read_lineup_forecasts():
    """Read experimental forecasts without modifying the audit database."""
    if not LINEUP_FORECAST_PATH.is_file():
        return []

    records = []

    with LINEUP_FORECAST_PATH.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            if not line.strip():
                continue

            try:
                record = json.loads(line)
            except json.JSONDecodeError as exc:
                raise HTTPException(
                    status_code=500,
                    detail=(
                        "Invalid JSON in the lineup forecast log "
                        f"at line {line_number}"
                    ),
                ) from exc

            if isinstance(record, dict):
                records.append(record)

    return records


def forecast_timestamp(record):
    value = record.get("forecast_generated_at_utc")

    if not value:
        return datetime.min.replace(tzinfo=timezone.utc)

    return datetime.fromisoformat(
        value.replace("Z", "+00:00")
    )


def latest_lineup_forecasts(records):
    """Prefer official-lineup forecasts over projected-lineup forecasts."""
    latest = {}

    for record in records:
        try:
            match_id = int(record["match_id"])
        except (KeyError, TypeError, ValueError):
            continue

        lineup_type = record.get("lineup_type", "projected")

        # Official lineups take precedence over projected ones.
        priority = (
            1 if lineup_type == "official_lineup" else 0,
            int(record.get("lineup_revision", 0)),
            forecast_timestamp(record),
        )

        previous = latest.get(match_id)

        if previous is None or priority > previous[0]:
            latest[match_id] = (priority, record)

    return [item[1] for item in latest.values()]


def public_lineup_forecast(record):
    """Return the UI fields without calling an experimental forecast locked."""
    player = record.get("player_forecast", {})
    control = record.get("control_forecast", {})

    return {
        "match_id": record["match_id"],
        "season": record.get("season"),
        "matchweek": record.get("matchweek"),
        "kickoff_utc": record.get("kickoff_utc"),
        "home_team": record.get("home_team"),
        "away_team": record.get("away_team"),
        "model_version": record.get("forecast_model_version"),
        "base_model_version": record.get("base_model_version"),
        "lineup_type": record.get("lineup_type"),
        "lineup_revision": record.get("lineup_revision"),
        "forecast_generated_at_utc": record.get(
            "forecast_generated_at_utc"
        ),
        "lineup_saved_at_utc": record.get("lineup_saved_at_utc"),
        "forecast_status": "experimental",
        "is_locked": False,
        "player_adjustment_applied": record.get(
            "player_adjustment_applied"
        ),
        "forecast_hash": record.get("forecast_hash"),
        "probabilities": player.get("probabilities"),
        "expected_goals": player.get("expected_goals"),
        "scoreline_matrix": player.get("scoreline_matrix"),
        "control_forecast": control,
        "player_forecast": player,
        "home_lineup_feature": record.get("home_lineup_feature"),
        "away_lineup_feature": record.get("away_lineup_feature"),
        "research_note": record.get("research_note"),
        "cold_start_reason": record.get("cold_start_reason"),
    }

class AnalystChatMessage(BaseModel):
    role: Literal["user", "assistant"]
    content: str = Field(min_length=1, max_length=2000)


class AnalystChatRequest(BaseModel):
    forecast_hash: str = Field(min_length=64, max_length=64)
    messages: list[AnalystChatMessage] = Field(
        min_length=1,
        max_length=12,
    )

