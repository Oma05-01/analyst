@app.get("/lineup-forecasts/upcoming")
def get_upcoming_lineup_forecasts(
    limit: int = Query(20, ge=1, le=50),
):
    """Returns upcoming experimental lineup forecasts from the JSONL log."""
    records = latest_lineup_forecasts(read_lineup_forecasts())
    now = datetime.now(timezone.utc)

    upcoming = []

    for record in records:
        kickoff_value = record.get("kickoff_utc")

        if not kickoff_value:
            continue

        try:
            kickoff = datetime.fromisoformat(
                kickoff_value.replace("Z", "+00:00")
            )
        except (ValueError, TypeError):
            continue

        if kickoff.tzinfo is None:
            continue

        if kickoff > now:
            upcoming.append(record)

    upcoming.sort(
        key=lambda record: forecast_timestamp(record)
        if not record.get("kickoff_utc")
        else datetime.fromisoformat(
            record["kickoff_utc"].replace("Z", "+00:00")
        )
    )

    forecasts = [
        public_lineup_forecast(record)
        for record in upcoming[:limit]
    ]

    return {
        "count": len(forecasts),
        "forecast_type": "experimental_lineup_adjusted",
        "forecasts": forecasts,
    }


@app.get("/predictions/upcoming")
def get_upcoming_predictions(response: Response, limit: int = Query(20, ge=1, le=50)):
    def produce():
        with db_cursor() as cur:
            cur.execute(
                """
                SELECT m.id, m.season, m.matchweek, m.kickoff_utc,
                       ht.name, awt.name,
                       p.p_home, p.p_draw, p.p_away,
                       p.expected_home_goals, p.expected_away_goals,
                       p.scoreline_matrix, p.payload_hash, p.locked_at,
                       mp.text
                FROM predictions p
                JOIN matches m   ON p.match_id = m.id
                JOIN teams ht    ON m.home_team_id = ht.id
                JOIN teams awt   ON m.away_team_id = awt.id
                LEFT JOIN match_previews mp
                       ON mp.match_id = p.match_id AND mp.model_version = p.model_version
                WHERE p.model_version = %s
                  AND m.status = ANY(%s)
                  AND m.kickoff_utc > NOW()
                ORDER BY m.kickoff_utc ASC
                LIMIT %s
                """,
                (MODEL_VERSION, UPCOMING_STATUSES, limit),
            )
            rows = cur.fetchall()
        predictions = [{
            "match_id": r[0],
            "season": r[1],
            "matchweek": r[2],
            "kickoff_utc": iso(r[3]),
            "home_team": r[4],
            "away_team": r[5],
            "model_version": MODEL_VERSION,
            "probabilities": {"home_win": float(r[6]), "draw": float(r[7]), "away_win": float(r[8])},
            "expected_goals": {"home": float(r[9]), "away": float(r[10])},
            "scoreline_matrix": as_matrix(r[11]),
            "payload_hash": r[12],            # null for rows locked without a hash
            "locked_at": iso(r[13]),
            "match_preview_text": r[14],      # null until the pipeline has stored a preview
        } for r in rows]
        return {"count": len(predictions), "predictions": predictions}

    public_cache(response, 30)
    return cached(("upcoming", limit), 30, produce)


@app.get("/predictions/{match_id}/analysis")
def get_match_analysis(match_id: int, response: Response):
    """Serves the preview stored at lock time. Never calls the LLM."""
    with db_cursor() as cur:
        cur.execute(
            """
            SELECT ht.name, awt.name, p.p_home, p.p_draw, p.p_away,
                   p.expected_home_goals, p.expected_away_goals,
                   mp.text, mp.llm_model
            FROM predictions p
            JOIN matches m   ON p.match_id = m.id
            JOIN teams ht    ON m.home_team_id = ht.id
            JOIN teams awt   ON m.away_team_id = awt.id
            LEFT JOIN match_previews mp
                   ON mp.match_id = p.match_id AND mp.model_version = p.model_version
            WHERE m.id = %s AND p.model_version = %s
            """,
            (match_id, MODEL_VERSION),
        )
        row = cur.fetchone()
    if not row:
        raise HTTPException(status_code=404, detail="Prediction not found for match_id")

    home, away, p_h, p_d, p_a, xg_h, xg_a, text, llm_model = row
    public_cache(response, 60)
    if text:
        return {"match_id": match_id, "match": f"{home} vs {away}", "llm_insight": text,
                "source": "llm", "llm_model": llm_model}
    fallback = LLMAnalyst.fallback_preview(home, away, float(p_h), float(p_d), float(p_a),
                                           float(xg_h), float(xg_a))
    return {"match_id": match_id, "match": f"{home} vs {away}", "llm_insight": fallback,
            "source": "template", "llm_model": None}


@app.get("/predictions/{match_id}/proof")
def get_prediction_proof(match_id: int, response: Response):
    """Everything needed to recompute the stored SHA-256 hash independently."""
    with db_cursor() as cur:
        cur.execute(
            """
            SELECT p.p_home, p.p_draw, p.p_away, p.expected_home_goals, p.expected_away_goals,
                   p.scoreline_matrix, p.params, p.n_train, p.train_cutoff,
                   p.payload_hash, p.locked_at, m.kickoff_utc
            FROM predictions p JOIN matches m ON m.id = p.match_id
            WHERE p.match_id = %s AND p.model_version = %s
            """,
            (match_id, MODEL_VERSION),
        )
        row = cur.fetchone()
    if not row:
        raise HTTPException(status_code=404, detail="Prediction not found for match_id")

    (p_h, p_d, p_a, xg_h, xg_a, matrix, params, n_train, train_cutoff,
     stored_hash, locked_at, kickoff) = row
    result = {
        "match_id": match_id,
        "model_version": MODEL_VERSION,
        "algorithm": HASH_ALGORITHM,
        "locked_at": iso(locked_at),
        "kickoff_utc": iso(kickoff),
        "lock_lead_seconds": int((kickoff - locked_at).total_seconds()),
        "payload_hash_stored": stored_hash,
    }
    if stored_hash is None or params is None or n_train is None or train_cutoff is None:
        result.update({"verified": None, "payload": None,
                       "reason": "This row was locked without proof data."})
    else:
        params = json.loads(params) if isinstance(params, str) else params
        payload = build_payload(match_id, MODEL_VERSION, (p_h, p_d, p_a), (xg_h, xg_a),
                                as_matrix(matrix), params, n_train, train_cutoff)
        recomputed = canonical_hash(payload)
        result.update({"verified": recomputed == stored_hash,
                       "payload_hash_recomputed": recomputed, "payload": payload})
    public_cache(response, 300)
    return result


@app.get("/track-record/stats")
def get_track_record_stats(response: Response):
    """Live, locked predictions only. Backtest numbers are not in this response."""
    def produce():
        with db_cursor() as cur:
            cur.execute(
                """
                SELECT p.model_version, COUNT(*), AVG(ps.brier), AVG(ps.rps), AVG(ps.log_loss),
                       MIN(p.locked_at), MAX(p.locked_at)
                FROM prediction_scores ps JOIN predictions p ON p.id = ps.prediction_id
                GROUP BY p.model_version ORDER BY p.model_version
                """)
            models = [{"model_version": r[0], "n": r[1], "brier": fnum(r[2]), "rps": fnum(r[3]),
                       "log_loss": fnum(r[4]), "first_locked": iso(r[5]), "last_locked": iso(r[6])}
                      for r in cur.fetchall()]

            cur.execute(
                """
                SELECT p.model_version, m.season, m.matchweek, COUNT(*),
                       AVG(ps.brier), AVG(ps.rps), AVG(ps.log_loss)
                FROM prediction_scores ps
                JOIN predictions p ON p.id = ps.prediction_id
                JOIN matches m ON m.id = p.match_id
                GROUP BY p.model_version, m.season, m.matchweek
                ORDER BY MIN(m.kickoff_utc), p.model_version
                """)
            by_matchweek = [{"model_version": r[0], "season": r[1], "matchweek": r[2], "n": r[3],
                             "brier": fnum(r[4]), "rps": fnum(r[5]), "log_loss": fnum(r[6])}
                            for r in cur.fetchall()]

            cur.execute(
                """
                SELECT p.p_home, p.p_draw, p.p_away, ps.outcome
                FROM prediction_scores ps JOIN predictions p ON p.id = ps.prediction_id
                WHERE p.model_version = %s
                """, (MODEL_VERSION,))
            scored = cur.fetchall()

        # Calibration: pool the three outcome probabilities of every prediction into 10 bins.
        bins = [{"low": i / 10, "high": (i + 1) / 10, "n": 0, "sum_p": 0.0, "hits": 0} for i in range(10)]
        for p_h, p_d, p_a, outcome in scored:
            for prob, label in ((p_h, "HOME"), (p_d, "DRAW"), (p_a, "AWAY")):
                b = bins[min(int(float(prob) * 10), 9)]
                b["n"] += 1
                b["sum_p"] += float(prob)
                b["hits"] += 1 if outcome == label else 0
        calibration = [{"low": b["low"], "high": b["high"], "n": b["n"],
                        "mean_predicted": b["sum_p"] / b["n"] if b["n"] else None,
                        "observed_rate": b["hits"] / b["n"] if b["n"] else None}
                       for b in bins]
        return {
            "primary_model": MODEL_VERSION,
            "baseline_model": BASELINE_VERSION,
            "scope": "live locked predictions only",
            "scoring_notes": "Brier is summed over three classes (range 0-2); RPS is normalised "
                             "(range 0-1); log loss is natural log. Lower is better for all.",
            "models": models,
            "by_matchweek": by_matchweek,
            "calibration": calibration,
        }

    public_cache(response, 60)
    return cached(("track-stats",), 60, produce)


@app.get("/track-record/predictions")
def get_track_record_predictions(response: Response,
                                 limit: int = Query(50, ge=1, le=200),
                                 offset: int = Query(0, ge=0)):
    """Audit list: each locked prediction with when it was locked and, once played, the result."""
    with db_cursor() as cur:
        cur.execute("SELECT COUNT(*) FROM predictions WHERE model_version = %s", (MODEL_VERSION,))
        total = cur.fetchone()[0]
        cur.execute(
            """
            SELECT m.id, m.season, m.matchweek, m.kickoff_utc, ht.name, awt.name,
                   p.p_home, p.p_draw, p.p_away, p.locked_at, p.payload_hash,
                   m.home_goals, m.away_goals, ps.outcome, ps.brier, ps.rps, ps.log_loss
            FROM predictions p
            JOIN matches m ON m.id = p.match_id
            JOIN teams ht  ON m.home_team_id = ht.id
            JOIN teams awt ON m.away_team_id = awt.id
            LEFT JOIN prediction_scores ps ON ps.prediction_id = p.id
            WHERE p.model_version = %s
            ORDER BY m.kickoff_utc DESC, m.id DESC
            LIMIT %s OFFSET %s
            """,
            (MODEL_VERSION, limit, offset),
        )
        rows = cur.fetchall()
    items = [{
        "match_id": r[0], "season": r[1], "matchweek": r[2], "kickoff_utc": iso(r[3]),
        "home_team": r[4], "away_team": r[5],
        "probabilities": {"home_win": float(r[6]), "draw": float(r[7]), "away_win": float(r[8])},
        "locked_at": iso(r[9]),
        "lock_lead_seconds": int((r[3] - r[9]).total_seconds()),
        "payload_hash": r[10],
        "result": ({"home_goals": r[11], "away_goals": r[12], "outcome": r[13]}
                   if r[13] is not None else None),
        "scores": ({"brier": fnum(r[14]), "rps": fnum(r[15]), "log_loss": fnum(r[16])}
                   if r[13] is not None else None),
    } for r in rows]
    public_cache(response, 60)
    return {"model_version": MODEL_VERSION, "total": total, "limit": limit, "offset": offset,
            "predictions": items}

@app.post("/lineup-forecasts/{match_id}/chat")
def chat_about_lineup_forecast(
    match_id: int,
    payload: AnalystChatRequest,
):
    """Live conversational analysis of a saved lineup-aware forecast."""

    if payload.messages[-1].role != "user":
        raise HTTPException(
            status_code=422,
            detail="The last message must be a user question.",
        )

    records = read_lineup_forecasts()

    forecast = next(
        (
            item
            for item in reversed(records)
            if str(item.get("match_id")) == str(match_id)
            and item.get("forecast_hash") == payload.forecast_hash
        ),
        None,
    )

    if forecast is None:
        raise HTTPException(
            status_code=404,
            detail="That forecast snapshot was not found. Refresh the page.",
        )

    analyst = LLMAnalyst()

    if not analyst.available:
        raise HTTPException(
            status_code=503,
            detail="The AI Analyst is unavailable: GROQ_API_KEY is not configured.",
        )

    control = forecast.get("control_forecast") or {}
    player = forecast.get("player_forecast") or {}

    control_probs = control.get("probabilities") or {}
    player_probs = player.get("probabilities") or {}

    control_xg = control.get("expected_goals") or {}
    player_xg = player.get("expected_goals") or {}


    def number(value, places=2, signed=False):
        if value is None:
            return None

        try:
            value = float(value)
        except (TypeError, ValueError):
            return None

        if not math.isfinite(value):
            return None

        return f"{value:+.{places}f}" if signed else f"{value:.{places}f}"


    def percentage(value):
        if value is None:
            return None

        try:
            value = float(value)
        except (TypeError, ValueError):
            return None

        if not math.isfinite(value):
            return None

        return f"{value * 100:.1f}%"


    def lineup_summary(side):
        feature = forecast.get(f"{side}_lineup_feature") or {}

        return {
            "team": feature.get("team"),
            "feature_status": feature.get("feature_status"),
            "raw_delta": number(
                feature.get("lineup_delta_raw"), 3, signed=True
            ),
            "standardized_delta": number(
                feature.get("lineup_delta_standardized"), 2, signed=True
            ),
        }


    context = {
        "match": {
            "home_team": forecast.get("home_team"),
            "away_team": forecast.get("away_team"),
            "kickoff_utc": forecast.get("kickoff_utc"),
            "lineup_type": forecast.get("lineup_type"),
            "lineup_revision": forecast.get("lineup_revision"),
        },
        "model_versions": {
            "baseline": control.get("model_version"),
            "lineup_adjusted": player.get("model_version"),
        },
        "published_figures": {
            "baseline": {
                "home_win": percentage(control_probs.get("home_win")),
                "draw": percentage(control_probs.get("draw")),
                "away_win": percentage(control_probs.get("away_win")),
                "home_expected_goals": number(control_xg.get("home")),
                "away_expected_goals": number(control_xg.get("away")),
            },
            "lineup_adjusted": {
                "home_win": percentage(player_probs.get("home_win")),
                "draw": percentage(player_probs.get("draw")),
                "away_win": percentage(player_probs.get("away_win")),
                "home_expected_goals": number(player_xg.get("home")),
                "away_expected_goals": number(player_xg.get("away")),
            },
        },
        "lineup_features": {
            "home": lineup_summary("home"),
            "away": lineup_summary("away"),
        },
        "research_note": forecast.get("research_note"),
        "interpretation_limit": (
            "Lineup deltas are attacking XGI/90 proxies relative to recent "
            "team-lineup averages. They do not directly establish overall "
            "player quality, chemistry, defensive strength or tactical roles."
        ),
    }
    try:
        reply = analyst.generate_chat_reply(
            [message.model_dump() for message in payload.messages],
            context,
        )
    except PreviewError as exc:
        # Keep internal provider details out of the public error response.
        raise HTTPException(
            status_code=502,
            detail="The AI Analyst couldn't respond just now. Try again shortly.",
        ) from exc

    return {
        "match_id": match_id,
        "reply": reply,
        "llm_model": analyst.model,
    }