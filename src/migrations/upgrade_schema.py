"""
Idempotent schema migration for the prediction pipeline.

Run from the repository root:   python -m src.migrations.upgrade_schema

What it enforces in the database (not just in Python):
  * predictions rows can never be updated or deleted, and the table cannot be truncated
  * a prediction can only be inserted BEFORE kickoff, and locked_at is always the
    database clock at insert time (the job cannot backdate it)
  * one prediction per (match_id, model_version)
  * LLM previews live in their own table so a failed or regenerated preview never
    touches a locked prediction

Limits: the table owner can still drop these triggers. For stronger guarantees give
the cron job a role with INSERT/SELECT only, and the API a SELECT-only role, and keep
the owner credentials out of both. The payload_hash + public commits are the external check.

Do not edit this file to change old behaviour: add a new migration file instead.
"""
import logging

from src.db import get_db_connection

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")

NUMERIC_COLUMNS = ("p_home", "p_draw", "p_away", "expected_home_goals", "expected_away_goals")

PREDICTION_COLUMNS_SQL = """
ALTER TABLE predictions
    ADD COLUMN IF NOT EXISTS params JSONB,
    ADD COLUMN IF NOT EXISTS n_train INT,
    ADD COLUMN IF NOT EXISTS train_cutoff TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS payload_hash TEXT,
    ADD COLUMN IF NOT EXISTS match_preview_text TEXT;
"""

CONSTRAINTS_SQL = """
CREATE UNIQUE INDEX IF NOT EXISTS ux_predictions_match_model
    ON predictions (match_id, model_version);

CREATE UNIQUE INDEX IF NOT EXISTS ux_prediction_scores_prediction
    ON prediction_scores (prediction_id);

-- locked_at is assigned by the database clock (the trigger below also enforces it)
ALTER TABLE predictions ALTER COLUMN locked_at SET DEFAULT clock_timestamp();
"""

MATCH_PREVIEWS_SQL = """
CREATE TABLE IF NOT EXISTS match_previews (
    id            SERIAL PRIMARY KEY,
    match_id      INT NOT NULL REFERENCES matches(id),
    model_version TEXT NOT NULL,
    text          TEXT NOT NULL,
    llm_model     TEXT,
    generated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (match_id, model_version)
);
"""

TRIGGERS_SQL = """
-- 1. no UPDATE / DELETE on predictions
CREATE OR REPLACE FUNCTION forbid_locked_prediction_change()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'Prediction ID % is locked and immutable.', OLD.id;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_predictions_immutable ON predictions;
CREATE TRIGGER trg_predictions_immutable
BEFORE UPDATE OR DELETE ON predictions
FOR EACH ROW EXECUTE FUNCTION forbid_locked_prediction_change();

-- 2. no TRUNCATE (statement-level triggers have no OLD row, so this needs its own function)
CREATE OR REPLACE FUNCTION forbid_prediction_truncate()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'The predictions table is immutable and cannot be truncated.';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_predictions_no_truncate ON predictions;
CREATE TRIGGER trg_predictions_no_truncate
BEFORE TRUNCATE ON predictions
FOR EACH STATEMENT EXECUTE FUNCTION forbid_prediction_truncate();

-- 3. inserts only before kickoff; locked_at is the database clock
CREATE OR REPLACE FUNCTION enforce_prediction_lock_rules()
RETURNS TRIGGER AS $$
DECLARE
    match_kickoff TIMESTAMPTZ;
BEGIN
    SELECT kickoff_utc INTO match_kickoff FROM matches WHERE id = NEW.match_id;
    IF match_kickoff IS NULL THEN
        RAISE EXCEPTION 'Cannot lock prediction: match % not found or has no kickoff time', NEW.match_id;
    END IF;
    IF clock_timestamp() >= match_kickoff THEN
        RAISE EXCEPTION 'Cannot lock prediction for match % at or after kickoff (%)', NEW.match_id, match_kickoff;
    END IF;
    NEW.locked_at := clock_timestamp();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_predictions_lock_rules ON predictions;
CREATE TRIGGER trg_predictions_lock_rules
BEFORE INSERT ON predictions
FOR EACH ROW EXECUTE FUNCTION enforce_prediction_lock_rules();
"""


def check_column_types(cursor):
    """Hashes are computed over full-precision floats, so the stored values must be too."""
    cursor.execute(
        """
        SELECT column_name, data_type
        FROM information_schema.columns
        WHERE table_name = 'predictions' AND column_name = ANY(%s)
        """,
        (list(NUMERIC_COLUMNS),),
    )
    wrong = [(name, dtype) for name, dtype in cursor.fetchall() if dtype != "double precision"]
    for name, dtype in wrong:
        logging.warning(
            "predictions.%s is %s, not double precision: Postgres rounds on insert, so stored values "
            "will not match the hashed ones. To fix, run: ALTER TABLE predictions "
            "ALTER COLUMN %s TYPE DOUBLE PRECISION;", name, dtype, name,
        )
    if not wrong:
        logging.info("Probability columns are double precision. OK.")


def upgrade_schema():
    conn = get_db_connection()
    try:
        with conn.cursor() as cursor:
            logging.info("Updating predictions table columns...")
            cursor.execute(PREDICTION_COLUMNS_SQL)

            logging.info("Adding unique constraints and the locked_at default...")
            cursor.execute(CONSTRAINTS_SQL)

            logging.info("Creating match_previews table...")
            cursor.execute(MATCH_PREVIEWS_SQL)

            logging.info("Installing immutability and lock-rule triggers...")
            cursor.execute(TRIGGERS_SQL)

            check_column_types(cursor)
        conn.commit()
        logging.info("Migration applied successfully!")
    except Exception:
        conn.rollback()
        logging.exception("Migration failed; nothing was changed.")
        raise
    finally:
        conn.close()


if __name__ == "__main__":
    upgrade_schema()